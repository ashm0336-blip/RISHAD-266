
/* ═══ صيغة النِسَب المعتمدة في كل الموقع ═══
   أقل من 10٪ تُعرض بمنزلة عشرية (0.3٪ بدل 0٪ المضلِّلة)، و10٪ فأكثر رقماً صحيحاً.
   وما دون 0.05٪ يُعرض «<0.1» لأن تقريبه لصفر يخفي وجوده أصلاً.
   تستقبل النسبة الخام (0–100) وتُعيد نصاً بلا علامة ٪ — العلامة تُضاف في موضع العرض. */
KIVO.bsPct = function (v) {
  var n = Number(v);
  if (!isFinite(n)) return "0";
  var a = Math.abs(n);
  if (a === 0) return "0";
  if (a < 0.05) return (n < 0 ? "-" : "") + "<0.1";
  if (a < 10) return n.toFixed(1).replace(/\.0$/, "");
  return String(Math.round(n));
};
