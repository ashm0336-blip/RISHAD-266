/* Derive the Worker function from the existing permission-slice implementation.
 * Usage: node tools/dept_permission_slice.mjs src
 * Writes the derived function to stdout; never edits source or contacts a service.
 * Parsing only: no evaluation, duplicated policy, or new permissions engine. */
import fs from 'node:fs';
import path from 'node:path';
import { parse } from '../node_modules/acorn/dist/acorn.mjs';
const source=fs.readFileSync(path.resolve(process.argv[2],'services/320-dept-storage.js'),'utf8');
const tree=parse(source,{ecmaVersion:'latest',sourceType:'script'}), matches=[];
function visit(node){
 if(!node||typeof node!=='object')return;
 if(node.type==='Property'&&node.key?.name==='permSlice')matches.push(node.value);
 for(const value of Object.values(node))Array.isArray(value)?value.forEach(visit):visit(value);
}
visit(tree);
if(matches.length!==1||matches[0].type!=='FunctionExpression')throw Error('Expected the single existing permSlice function');
process.stdout.write('/* Generated by tools/generate.py from services/320-dept-storage.js; do not edit. */\nvar rsPermSlice = '+source.slice(matches[0].start,matches[0].end)+';\n');
